#!/usr/bin/env python3
"""Reverse exactly the P2/P4 shared Vulkan occlusion query bank edit.

Historical Samples/TFB full-file hash witnesses remain pinned to their
reviewed predecessor. This helper strips ONLY the byte-exact active
CloseCounter delta generated by prepare-vulkan-port.py; it cannot hide
unrelated renderer source drift.
"""
import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GENERATOR = ROOT/"tools/prepare-vulkan-port.py"
OWNER = ROOT/"vendor/encore-active/eden-vulkan/vulkan_query_cache.cpp"
TAG = "P2/P4 bounded native occlusion query bank lifetime"

def strip_reviewed_close(source: str) -> str:
    tree = ast.parse(GENERATOR.read_text())
    matches = []
    for statement in tree.body:
        if not isinstance(statement, ast.Expr):
            continue
        call = statement.value
        if not isinstance(call, ast.Call) or not isinstance(call.func, ast.Name):
            continue
        if call.func.id != "apply_reviewed_delta" or len(call.args) != 4:
            continue
        try:
            name, old, new, label = map(ast.literal_eval, call.args)
        except (ValueError, TypeError):
            continue
        if label == TAG:
            matches.append((name, old, new))
    assert len(matches) == 1, "occlusion generator source drift"
    name, old, new = matches[0]
    assert name == "vulkan_query_cache.cpp"
    assert "PauseCounter();" in old and "ResetCounter();" not in old
    assert new.count("ResetCounter();") == 1
    assert "SamplesQueryBank::BANK_SIZE" in new
    assert source.count(new) == 1, "occlusion source no longer matches generated delta"
    assert source.count(old) == 0, "old and new CloseCounter mixed"
    return source.replace(new, old)
