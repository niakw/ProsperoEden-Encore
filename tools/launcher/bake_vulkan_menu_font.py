#!/usr/bin/env python3
"""Generate the Vulkan quick-menu ASCII atlas from the launcher's baked Montserrat font.

The output is intentionally descriptor-free: each 24x28 glyph is stored as two
1-bit coverage planes (four alpha levels) consumed by vulkan_hud.frag. This
keeps the existing post-process HUD pipeline and avoids any guest-frame readback
or per-frame allocation.
"""
from __future__ import annotations
import argparse, pathlib, struct

ROOT=pathlib.Path(__file__).resolve().parents[2]
FONT=ROOT/"headless/prosperoeden/ui/fonts/montserrat-medium.pefont"
parser=argparse.ArgumentParser()
parser.add_argument("--output", type=pathlib.Path,
                    default=ROOT/"headless/vulkan_menu_font.glsl")
args=parser.parse_args()
OUT=args.output
W,H,SIZE=24,28,22.0
HEADER="<IIHHfffffII"
GLYPH="<IHHHHfff"
HS=struct.calcsize(HEADER); GS=struct.calcsize(GLYPH); KS=12

data=FONT.read_bytes()
magic,version,aw,ah,pixel,sdf_range,ascent,descent,line_gap,gcount,kcount=struct.unpack_from(HEADER,data,0)
assert magic==0x46505A50 and version==1 and pixel>0
glyphs={}
off=HS
for _ in range(gcount):
    row=struct.unpack_from(GLYPH,data,off);off+=GS
    glyphs[row[0]]=row
atlas_off=HS+gcount*GS+kcount*KS
atlas=data[atlas_off:atlas_off+aw*ah]
assert len(atlas)==aw*ah
scale=SIZE/pixel
baseline=max(2,min(H-2,round(ascent*scale)+2))

def sdf_at(x,y):
    x=max(0,min(aw-1,x)); y=max(0,min(ah-1,y))
    return atlas[y*aw+x]

def planes(cp):
    g=glyphs.get(cp) or glyphs[ord("?")]
    _,gx,gy,gw,gh,ox,oy,advance=g
    pen=max(1.0,(W-advance*scale)*0.5)
    lo=[];hi=[]
    for ty in range(H):
        lm=hm=0
        for tx in range(W):
            relx=(tx+0.5-pen)/scale
            rely=(ty+0.5-baseline)/scale
            level=0
            sx=relx-ox; sy=rely-oy
            if 0<=sx<gw and 0<=sy<gh:
                v=sdf_at(gx+int(sx),gy+int(sy))
                # Four stable coverage levels around the SDF edge (128).
                level=0 if v<96 else 1 if v<120 else 2 if v<144 else 3
            bit=1<<(W-1-tx)
            if level&1: lm|=bit
            if level&2: hm|=bit
        lo.append(lm);hi.append(hm)
    return lo,hi

low=[]; high=[]
for cp in range(32,127):
    lo,hi=planes(cp); low+=lo; high+=hi

def array(name,values):
    rows=[]
    for i in range(0,len(values),8):
        rows.append("    "+", ".join(f"0x{v:06x}u" for v in values[i:i+8]))
    return f"const uint {name}[{len(values)}] = uint[{len(values)}](\n"+",\n".join(rows)+"\n);\n"

out="""// Generated by tools/launcher/bake_vulkan_menu_font.py from the same
// montserrat-medium.pefont used by the launcher. Do not hand-edit.
const int MENU_FONT_FIRST = 32;
const int MENU_FONT_LAST = 126;
const int MENU_FONT_W = 24;
const int MENU_FONT_H = 28;
"""
out+=array("MENU_FONT_LOW",low)
out+=array("MENU_FONT_HIGH",high)
out+=r'''
float menuFontAlpha(uint codepoint, int x, int y) {
    if (x < 0 || x >= MENU_FONT_W || y < 0 || y >= MENU_FONT_H) return 0.0;
    uint cp = (codepoint >= uint(MENU_FONT_FIRST) && codepoint <= uint(MENU_FONT_LAST))
        ? codepoint : 63u;
    int index = (int(cp) - MENU_FONT_FIRST) * MENU_FONT_H + y;
    uint bit = 1u << uint(MENU_FONT_W - 1 - x);
    uint level = ((MENU_FONT_LOW[index] & bit) != 0u ? 1u : 0u) |
                 ((MENU_FONT_HIGH[index] & bit) != 0u ? 2u : 0u);
    return float(level) / 3.0;
}
'''
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text(out)
print(f"{OUT}: ascii=95 cell={W}x{H} rows={len(low)} bytes={OUT.stat().st_size}")
