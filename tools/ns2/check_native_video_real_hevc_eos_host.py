#!/usr/bin/env python3
"""H05: execute maintained native HEVC Decode + Drain + Render, real FFmpeg.

The 96-byte synthetic one-frame 16x16 HEVC Annex-B test stream contains
only VPS/SPS/PPS/IDR, generated by FFmpeg libx265 and stripped of metadata.
The REAL native decoder implementation is compiled, while unused NS1 wrapper
APIs are isolated in a stub. Not a proof of guest TIPC or Vulkan fences.
"""
from pathlib import Path
import os
import shutil
import subprocess
import tempfile

ROOT=Path(__file__).resolve().parents[2]
OWNER=ROOT/"vendor/encore-active/ns2-runtime/video_decoder/video_core/host1x/nx2_video_decoder.cpp"
source=OWNER.read_text()
def extract(start, stop):
    assert source.count(start)==source.count(stop)==1,(start,stop)
    return start+source.split(start,1)[1].split(stop,1)[0]

helpers=extract("std::optional<NvdecCommon::VideoCodec> CodecFromMime(", "\n} // namespace\n\nbool IsH264Stream(")
real=extract("struct Nx2VideoDecoder::Impl {", "\n} // namespace Tegra::Host1x")
for check in ("bool Nx2VideoDecoder::Decode(", "bool Nx2VideoDecoder::Drain(",
              "bool Nx2VideoDecoder::Render(", "avcodec_receive_frame(", 
              "avcodec_send_packet(", "IsSafeNativeVideoPacketInput(",
              "pending_pts.merge(staged_pts)", "sws_getCachedContext("):
    assert check in real,check

fixture=r"""
#include <algorithm>
#include <array>
#include <cassert>
#include <cstdint>
#include <cstring>
#include <limits>
#include <memory>
#include <optional>
#include <set>
#include <span>
#include <string>
#include <string_view>
#include <vector>
#include <cstdio>
extern "C" {
#include <libavcodec/avcodec.h>
#include <libavutil/pixdesc.h>
#include <libswscale/swscale.h>
}
using u8=std::uint8_t;using u32=std::uint32_t;using u64=std::uint64_t;
using s32=std::int32_t;using s64=std::int64_t;
#define LOG_INFO(...) ((void)0)
#define LOG_ERROR(...) ((void)0)
namespace NvdecCommon {enum class VideoCodec{VP9,VP8,H264};}
namespace Settings {
enum class NvdecEmulation{Cpu,Gpu};
struct Choice{NvdecEmulation GetValue()const{return NvdecEmulation::Cpu;}};
struct Values{Choice nvdec_emulation;};
inline Values values;
}
namespace FFmpeg {
class Frame {
    AVFrame* frame;
public:
    Frame():frame(av_frame_alloc()) { assert(frame); }
    ~Frame(){av_frame_free(&frame);}
    Frame(const Frame&)=delete;Frame& operator=(const Frame&)=delete;
    AVFrame* GetFrame() {return frame;}
    const AVFrame* GetFrame() const{return frame;}
};
class Packet {
    AVPacket* packet;
public:
    explicit Packet(std::span<const u8> bytes):packet(av_packet_alloc()) {
        assert(packet && bytes.size()<=static_cast<std::size_t>(INT32_MAX));
        assert(av_new_packet(packet,static_cast<int>(bytes.size()))==0);
        std::memcpy(packet->data,bytes.data(),bytes.size());
    }
    ~Packet(){av_packet_free(&packet);}
    AVPacket* GetPacket(){return packet;}
};
struct Decoder {
    explicit Decoder(NvdecCommon::VideoCodec){}
    const AVCodec* GetCodec()const{return nullptr;}
};
struct DecoderContext {
    explicit DecoderContext(Decoder&){}
    bool OpenContext(Decoder&){return false;}
    AVCodecContext* GetCodecContext(){return nullptr;}
    bool SendPacket(Packet&){return false;}
    std::shared_ptr<Frame> ReceiveFrame(){return {};}
};
struct HardwareContext {
    void InitializeForDecoder(DecoderContext&,Decoder&){}
};
}
#include "video_core/host1x/h264_packet.h"
namespace Tegra::Host1x {
struct Nx2Picture {
    u32 width{},height{};u64 pts{};
    std::shared_ptr<FFmpeg::Frame> frame;
};
enum class Nx2PictureFormat:u32 {Nv12,Rgba8,Bgra8};
class Nx2VideoDecoder {
public:
    explicit Nx2VideoDecoder(std::string_view);
    ~Nx2VideoDecoder();
    bool IsOpen()const;
    const std::string& Name()const;
    bool Decode(std::span<const u8>,u64,std::vector<Nx2Picture>&);
    bool Drain(std::vector<Nx2Picture>&);
    void Reset();
    bool Render(const Nx2Picture&,Nx2PictureFormat,u32,u32,u64,u64,std::span<u8>);
private:
    struct Impl;std::unique_ptr<Impl> impl;
};
namespace {
__REAL_HELPERS__
}
__REAL_OWNER__
}
int main(){
    // Generated 16x16 solid-red 4:2:0 HEVC/Annex-B, no SEI metadata.
    constexpr std::array<u8,__SIZE__> data{__BYTES__};
    using namespace Tegra::Host1x;
    Nx2VideoDecoder unsupported{"video/unknown"};
    assert(!unsupported.IsOpen());
    std::vector<Nx2Picture> rejected;
    assert(!unsupported.Decode(data,41,rejected) && rejected.empty());
    Nx2VideoDecoder codec{"video/hevc"};
    assert(codec.IsOpen() && codec.Name()=="video/hevc");
    assert(!codec.Decode({},41,rejected));
    assert(!codec.Decode(data,static_cast<u64>(INT64_MAX)+1,rejected));
    assert(rejected.empty());
    std::vector<Nx2Picture> images;
    assert(codec.Decode(data,42,images));
    assert(codec.Drain(images));
    assert(images.size()==1 && images[0].frame);
    assert(images[0].width==16 && images[0].height==16);
    assert(images[0].pts==42);
    constexpr std::size_t luma=16*16;
    constexpr std::size_t pixels=luma+(16*8);
    std::vector<u8> guest(pixels+16,0xee);
    assert(codec.Render(images[0],Nx2PictureFormat::Nv12,16,16,16,luma,
                        std::span<u8>{guest.data(),pixels}));
    assert(std::any_of(guest.begin(),guest.begin()+pixels,[](u8 b){return b!=0xee;}));
    assert(std::all_of(guest.begin()+pixels,guest.end(),[](u8 b){return b==0xee;}));
    // The valid decoded frame must survive the decoder's post-EOS Reset.
    assert(images[0].frame->GetFrame()->width==16);
    assert(images[0].frame->GetFrame()->height==16);
    std::vector<Nx2Picture> extra;
    codec.Reset();
    assert(codec.IsOpen() && extra.empty());
    std::puts("H05_REAL_NATIVE_HEVC_DECODE_DRAIN_RENDER_PASS"
              " compressed_bytes=96 frames=1 pts=42 eos_drained=1"
              " guest_nv12=written overflow_canary=clean"
              " invalid_codec=refused oversized_pts=refused"
              " guest_ipc_vulkan_fences=not_exercised");
}
"""
# Using the included actual maintainer header for H264/HEVC framing.
packed=bytes.fromhex("0000000140010c01ffff0408000003009fa800000300001eba0240000000014201010408000003009fa800000300001ea0884596e96f0bc05a020000030002000003003210000000014401c07181120000012801ade0c7a7fda3efea0e875427")
assert len(packed)==96
code=fixture.replace("__REAL_HELPERS__",helpers).replace("__REAL_OWNER__",real)
code=code.replace("__SIZE__",str(len(packed)))
code=code.replace("__BYTES__",",".join("0x%02x"%x for x in packed))
compilers=list(dict.fromkeys(x for x in (shutil.which("clang++"),shutil.which("g++")) if x))
assert compilers
with tempfile.TemporaryDirectory(prefix="eden-h05-native-hevc-") as temp:
    file=Path(temp)/"hevc.cpp";file.write_text(code)
    for cc in compilers:
        for opt in ("-O0","-O2"):
            exe=Path(temp)/(Path(cc).name.replace("+","p")+opt)
            cmd=[cc,"-std=c++20",opt,"-Wall","-Wextra","-Werror",
                 "-Wno-unused-variable","-Wno-unused-function",
                 "-fsanitize=undefined","-fno-sanitize-recover=all",
                 "-I"+str(ROOT/"vendor/encore-active/ns2-runtime/video_decoder"),
                 "-I"+str(ROOT/"vendor/sources/eden/src"),
                 str(file),"-o",str(exe),"-lavcodec","-lavutil","-lswscale"]
            built=subprocess.run(cmd,capture_output=True,text=True,timeout=70,env=os.environ.copy())
            assert built.returncode==0,(cc,built.stderr[-6000:])
            result=subprocess.run([str(exe)],capture_output=True,text=True,timeout=25,env=os.environ.copy())
            assert result.returncode==0,(cc,result.stdout[-2200:],result.stderr[-5200:])
            print(Path(cc).name,opt,result.stdout.strip(),flush=True)
