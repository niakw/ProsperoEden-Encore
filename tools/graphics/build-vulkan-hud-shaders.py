#!/usr/bin/env python3
"""Build the exact native Vulkan HUD shaders into one deterministic C++ header.

The fragment source may include build-local generated GLSL such as the
Montserrat quick-menu atlas. This tool is shared by native CMake and host CI so
the PS5 package cannot silently keep an older vendored SPIR-V HUD.
"""
from __future__ import annotations

import argparse
import pathlib
import struct
import subprocess
import tempfile

parser = argparse.ArgumentParser()
parser.add_argument("--glslang", required=True)
parser.add_argument("--spirv-val", required=True)
parser.add_argument("--source-dir", type=pathlib.Path, required=True)
parser.add_argument("--include-dir", type=pathlib.Path, required=True)
parser.add_argument("--output", type=pathlib.Path, required=True)
parser.add_argument("--spv-dir", type=pathlib.Path)
args = parser.parse_args()

source_dir = args.source_dir.resolve()
include_dir = args.include_dir.resolve()
args.output.parent.mkdir(parents=True, exist_ok=True)
if args.spv_dir:
    args.spv_dir.mkdir(parents=True, exist_ok=True)

def build(stage: str, source: pathlib.Path, variable: str, quick: bool = False,
          artwork: bool = False) -> tuple[str, list[int]]:
    if args.spv_dir:
        suffix = ".quick.spv" if quick else ".loading.spv" if artwork else ".spv"
        spv = args.spv_dir / (source.name + suffix)
        cleanup = None
    else:
        cleanup = tempfile.TemporaryDirectory(prefix="eden-hud-spv-")
        spv = pathlib.Path(cleanup.name) / f"{source.name}.spv"
    subprocess.run([
        args.glslang, "-V", "--target-env", "vulkan1.1", "-S", stage,
        f"-I{include_dir}", f"-I{source_dir}",
        *(["-DEDEN_QUICK_MENU=1"] if quick else []),
        *(["-DEDEN_LOADING_ARTWORK=1"] if artwork else []), "-o", str(spv), str(source)
    ], check=True)
    subprocess.run([args.spirv_val, "--target-env", "vulkan1.1", str(spv)], check=True)
    raw = spv.read_bytes()
    if len(raw) % 4:
        raise SystemExit(f"{source}: SPIR-V byte length is not 32-bit aligned")
    words = list(struct.unpack("<" + "I" * (len(raw) // 4), raw))
    if not words or words[0] != 0x07230203:
        raise SystemExit(f"{source}: invalid SPIR-V magic")
    if len(words) > 32768:
        raise SystemExit(f"{variable}: shader exceeds 128 KiB instruction/data budget ({len(words)} words)")
    if cleanup is not None:
        cleanup.cleanup()
    return variable, words

compiled = [
    build("vert", source_dir / "vulkan_hud.vert", "EDEN_HUD_VERT_SPV"),
    build("frag", source_dir / "vulkan_hud.frag", "EDEN_HUD_FRAG_SPV"),
    build("frag", source_dir / "vulkan_hud.frag", "EDEN_QUICK_MENU_FRAG_SPV", quick=True),
    build("frag", source_dir / "vulkan_hud.frag", "EDEN_LOADING_ARTWORK_FRAG_SPV", artwork=True),
]

lines = [
    "// Generated by tools/graphics/build-vulkan-hud-shaders.py. Do not hand-edit.",
    "#pragma once",
    "#include <cstdint>",
]
for variable, words in compiled:
    lines.append(f"inline constexpr std::uint32_t {variable}[] = {{")
    for i in range(0, len(words), 8):
        lines.append("    " + ", ".join(f"0x{word:08x}u" for word in words[i:i+8]) + ",")
    lines.append("};")
args.output.write_text("\n".join(lines) + "\n")
print(f"{args.output}: vert_words={len(compiled[0][1])} frag_words={len(compiled[1][1])} quick_words={len(compiled[2][1])}")
